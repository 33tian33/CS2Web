const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let pending=[],renders=0,html='';
const location={hash:'#/event/simulation'};
const context=vm.createContext({location,state:{old:true},api:path=>{assert.equal(path,'state');return new Promise((resolve,reject)=>pending.push({resolve,reject}))},clearTimeout(){},shell:value=>{html=value},render:()=>renders++,esc:s=>s});
vm.runInContext(fs.readFileSync('public/simulation.js','utf8'),context);
const run=code=>vm.runInContext(code,context);
(async()=>{
  run('simulatedResults={1:{id:1}};simulationResult={old:true};unlockedSimulationMatches.add(1)');
  const entry=run('enterSimulation()');
  assert.match(html,/正在同步/);
  const latest={matches:[{id:1,status:'finished'}]};
  pending.shift().resolve(latest);await entry;
  assert.equal(context.state,latest);
  assert.equal(run('Object.keys(simulatedResults).length'),0);
  assert.equal(run('unlockedSimulationMatches.size'),0);
  assert.equal(run('simulationResult'),null);
  assert.equal(renders,1);
  const oldRequest=run('enterSimulation()');
  const newRequest=run('enterSimulation()');
  const old=pending.shift(),current=pending.shift();
  current.resolve({version:2});await newRequest;
  old.resolve({version:1});await oldRequest;
  assert.equal(context.state.version,2);
  const leave=run('enterSimulation()');location.hash='#/event';pending.shift().resolve({version:3});await leave;
  assert.equal(context.state.version,2);
  location.hash='#/event/simulation';const failure=run('enterSimulation()');pending.shift().reject(Error('网络错误'));await failure;
  assert.match(html,/同步赛果失败/);assert.match(html,/重新同步/);
  assert.equal(context.state.version,2);
  console.log('Simulation entry: fresh data, reset, stale response protection, leave and retry passed');
})().catch(e=>{console.error(e);process.exitCode=1});
