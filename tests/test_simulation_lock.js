const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const match={id:7,stage:'group',flow_key:'groups:g0:0-1',team_a:1,team_b:2,status:'finished',bo:2,maps:[{scoreA:13,scoreB:5},{scoreA:13,scoreB:7}]};
const context=vm.createContext({state:{matches:[match]},team:id=>({name:String(id)}),teamIdentity:t=>t.name,score:m=>[m.maps.filter(x=>x.scoreA>x.scoreB).length,m.maps.filter(x=>x.scoreB>x.scoreA).length],$:()=>({}),clearTimeout(){},render(){}});
vm.runInContext(fs.readFileSync('public/simulation.js','utf8'),context);
vm.runInContext('queueSimulation=()=>{}',context);
const run=code=>vm.runInContext(code,context);
let html=run('simulationMatch(state.matches[0])');
assert.match(html,/is-locked/);
assert.match(html,/<select[^>]*disabled/);
assert.match(html,/<input[^>]*value="14" disabled/);
assert.match(html,/value="2:0" selected/);
run('toggleSimulationLock(7)');
html=run('simulationMatch(state.matches[0])');
assert.doesNotMatch(html,/disabled/);
assert.match(html,/恢复并锁定/);
run("setSimulationDiff(7,{value:'-18',setCustomValidity(){}})");
assert.equal(run('simulatedResults[7].unlocked'),true);
run('toggleSimulationLock(7)');
assert.equal(run('Object.keys(simulatedResults).length'),0);
assert.match(run('simulationMatch(state.matches[0])'),/value="14" disabled/);
run('toggleSimulationLock(7);resetSimulation()');
assert.equal(run('unlockedSimulationMatches.size'),0);
assert.equal(match.maps[0].scoreA,13);
console.log('Finished simulation: default lock, explicit unlock, restore and reset passed');
